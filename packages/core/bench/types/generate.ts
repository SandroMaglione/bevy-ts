/**
 * Generates `stress.ts`, the fixed program used by the type-level benchmark.
 *
 * The program models a mid-sized game: many components/resources/events,
 * machines, systems with mixed access, schedule composition, component
 * requirements (`Schema.requires`) on spawns, inserts, and removes, and
 * runtime requirement checking. Its checker metrics (types, instantiations) are
 * deterministic for a given TypeScript version, which makes them a stable CI
 * regression signal for the type architecture.
 *
 * Run with: node --import tsx packages/core/bench/types/generate.ts
 */
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const COMPONENTS = 32
const RESOURCES = 16
const EVENTS = 8
const SYSTEMS = 64

const pad = (value: number): string => value.toString().padStart(2, "0")
const lines: Array<string> = []
const emit = (line = ""): void => {
  lines.push(line)
}

emit("// Generated by generate.ts. Do not edit by hand.")
emit("import { Descriptor, Schema } from \"@typeonce/ritmo\"")
emit()
for (let index = 0; index < COMPONENTS; index++) {
  emit(`const C${pad(index)} = Descriptor.Component<{ readonly v${index}: number }>()("Stress/C${pad(index)}")`)
}
for (let index = 0; index < RESOURCES; index++) {
  emit(`const R${pad(index)} = Descriptor.Resource<number>()("Stress/R${pad(index)}")`)
}
for (let index = 0; index < EVENTS; index++) {
  emit(`const E${pad(index)} = Descriptor.Event<{ readonly e${index}: number }>()("Stress/E${pad(index)}")`)
}
emit("const Clock = Descriptor.Service<{ readonly now: () => number }>()(\"Stress/Clock\")")
emit("const { relation: ChildOf } = Descriptor.Hierarchy(\"Stress/ChildOf\", \"Stress/Children\")")
emit()
emit("const Game = Schema.bind(")
const componentKeys = Array.from({ length: COMPONENTS }, (_, index) => `C${pad(index)}`)
const resourceKeys = Array.from({ length: RESOURCES }, (_, index) => `R${pad(index)}`)
const eventKeys = Array.from({ length: EVENTS }, (_, index) => `E${pad(index)}`)
emit(`  Schema.fragment({ components: { ${componentKeys.slice(0, COMPONENTS / 2).join(", ")} }, resources: { ${resourceKeys.slice(0, RESOURCES / 2).join(", ")} }, events: { ${eventKeys.slice(0, EVENTS / 2).join(", ")} } }),`)
emit(`  Schema.fragment({ components: { ${componentKeys.slice(COMPONENTS / 2).join(", ")} }, resources: { ${resourceKeys.slice(RESOURCES / 2).join(", ")} }, events: { ${eventKeys.slice(EVENTS / 2).join(", ")} }, relations: { ChildOf } }),`)
// Requirements (a chain across fragments) on components no other section spawns: C28..C31.
emit("  Schema.fragment({ requires: [Schema.requires(C28, C29, C30), Schema.requires(C29, C31), Schema.requires(C30, C31)] })")
emit(")")
emit()
emit("const Flow = Game.StateMachine(\"Stress/Flow\", [\"Menu\", \"Playing\", \"Paused\"])")
emit()

for (let index = 0; index < SYSTEMS; index++) {
  const read = `C${pad(index % COMPONENTS)}`
  const write = `C${pad((index + 7) % COMPONENTS)}`
  const optional = `C${pad((index + 13) % COMPONENTS)}`
  const without = `C${pad((index + 21) % COMPONENTS)}`
  const resource = `R${pad(index % RESOURCES)}`
  const eventWrite = `E${pad(index % EVENTS)}`
  const eventRead = `E${pad((index + 3) % EVENTS)}`
  const readKey = `v${index % COMPONENTS}`
  const writeKey = `v${(index + 7) % COMPONENTS}`
  emit(`const S${pad(index)} = Game.System("Stress/S${pad(index)}", {`)
  emit("  queries: {")
  emit("    main: Game.Query({")
  emit(`      selection: { a: Game.Query.read(${read}), b: Game.Query.write(${write}), c: Game.Query.optional(${optional}) },`)
  emit(`      without: [${without}]`)
  emit("    })")
  emit("  },")
  emit(`  resources: { value: Game.System.writeResource(${resource}) },`)
  emit(`  events: { out: Game.System.writeEvent(${eventWrite}), in: Game.System.readEvent(${eventRead}) },`)
  if (index % 4 === 0) emit("  services: { clock: Game.System.service(Clock) },")
  if (index % 5 === 0) emit("  when: [Game.Condition.inState(Flow, \"Playing\")],")
  if (index % 8 === 0) emit("  nextMachines: { flow: Game.System.nextState(Flow) },")
  emit(`}, ({ queries, resources, events${index % 4 === 0 ? ", services" : ""}${index % 8 === 0 ? ", nextMachines" : ""} }) => {`)
  emit("  for (const { data } of queries.main.each()) {")
  emit(`    data.b.set({ ${writeKey}: data.a.get().${readKey} + (data.c.present ? 1 : 0) })`)
  emit("  }")
  emit(`  resources.value.update((value) => value + events.in.all().length)`)
  emit(`  events.out.emit({ e${index % EVENTS}: resources.value.get() })`)
  if (index % 4 === 0) emit("  void services.clock.now()")
  if (index % 8 === 0) emit("  nextMachines.flow.set(\"Paused\")")
  emit("})")
}
emit()

const groups = 4
const perGroup = SYSTEMS / groups
for (let group = 0; group < groups; group++) {
  const members = Array.from({ length: perGroup }, (_, index) => `S${pad(group * perGroup + index)}`)
  emit(`const Group${group} = Game.Schedule(${members.join(", ")}, Game.Schedule.applyDeferred())`)
}
emit("const Transitions = Game.Schedule.transitions(Game.Schedule.onEnter(Flow, \"Playing\", [S01]))")
emit(`const Update = Game.Schedule(${Array.from({ length: groups }, (_, group) => `Group${group}`).join(", ")}, Game.Schedule.applyStateTransitions(Transitions))`)
emit()
emit("const runtime = Game.Runtime.make({")
emit("  services: Game.Runtime.services(Game.Runtime.service(Clock, { now: () => 0 })),")
emit(`  resources: { ${resourceKeys.map((key) => `${key}: 0`).join(", ")} },`)
emit("  machines: Game.Runtime.machines(Game.Runtime.machine(Flow, \"Menu\"))")
emit("})")
emit()
emit("runtime.tick(Update)")
emit()
// A long schedule with thisTick reads: runtime.tick checks the order of every
// read against every writer that follows it.
const ORDER_WRITERS = 48
const ORDER_READERS = 8
for (let index = 0; index < ORDER_WRITERS; index++) {
  emit(`const W${pad(index)} = Game.System("Stress/W${pad(index)}", { events: { out: Game.System.writeEvent(E${pad(index % EVENTS)}) } }, ({ events }) => {`)
  emit(`  events.out.emit({ e${index % EVENTS}: ${index} })`)
  emit("})")
}
for (let index = 0; index < ORDER_READERS; index++) {
  emit(`const T${pad(index)} = Game.System("Stress/T${pad(index)}", { events: { in: Game.System.thisTick(Game.System.readEvent(E${pad(index % EVENTS)})) } }, ({ events }) => {`)
  emit("  void events.in.all()")
  emit("})")
}
const writers = Array.from({ length: ORDER_WRITERS }, (_, index) => `W${pad(index)}`)
const readers = Array.from({ length: ORDER_READERS }, (_, index) => `T${pad(index)}`)
emit(`const Ordered = Game.Schedule(${writers.join(", ")}, ${readers.join(", ")})`)
emit("runtime.tick(Ordered)")
emit(`// @ts-expect-error a writer after a thisTick reader is a compile error`)
emit(`runtime.tick(Game.Schedule(${readers.join(", ")}, ${writers.join(", ")}))`)
emit()
// A 150-system schedule with markers and thisTick reads of events and
// queries: 120 command writers in groups of 10, each group followed by an
// applyDeferred(), and 30 readers after the groups they need.
const LONG_GROUPS = 12
const LONG_GROUP_SIZE = 10
const long: Array<string> = []
for (let group = 0; group < LONG_GROUPS; group++) {
  for (let slot = 0; slot < LONG_GROUP_SIZE; slot++) {
    const index = group * LONG_GROUP_SIZE + slot
    const name = `L${index.toString().padStart(3, "0")}`
    // Each group owns one component (C16 + group) that only its writers spawn and insert.
    const a = `C${pad(index % 16)}`
    const b = `C${pad(16 + group)}`
    emit(`const ${name} = Game.System("Stress/${name}", { commands: Game.System.commands(Game.System.spawns(${a}, ${b}), Game.System.inserts(${b})) }, ({ commands }) => {`)
    emit(`  commands.spawn(Game.Command.spawn([${a}, { v${index % 16}: 0 }], [${b}, { v${16 + group}: 0 }]))`)
    emit("})")
    long.push(name)
  }
  long.push("Game.Schedule.applyDeferred()")
  for (let reader = 0; reader < 2; reader++) {
    const index = group * 2 + reader
    const name = `Q${pad(index)}`
    const c = `C${pad(16 + group)}`
    emit(`const ${name} = Game.System("Stress/${name}", { queries: { seen: Game.System.thisTick(Game.Query({ selection: { c: Game.Query.read(${c}) } })) } }, ({ queries }) => {`)
    emit("  void queries.seen.each()")
    emit("})")
    long.push(name)
  }
  if (group % 2 === 0) {
    const name = `X${pad(group / 2)}`
    emit(`const ${name} = Game.System("Stress/${name}", { events: { in: Game.System.thisTick(Game.System.readEvent(E${pad(group % EVENTS)})) } }, ({ events }) => {`)
    emit("  void events.in.all()")
    emit("})")
    long.push(name)
  }
}
emit(`const Long = Game.Schedule(${long.join(", ")})`)
emit("runtime.tick(Long)")
emit("// @ts-expect-error a command writer with no applyDeferred() before a thisTick query reader is a compile error")
emit(`runtime.tick(Game.Schedule(${long.filter((entry) => !entry.startsWith("Game.Schedule")).join(", ")}))`)
emit()
// Commands checked against Schema.requires: satisfied spawns, inserts proven
// by a query plus their entries, and removes of requirers with what they require.
const REQUIRE_SYSTEMS = 16
const requireSystems: Array<string> = []
for (let index = 0; index < REQUIRE_SYSTEMS; index++) {
  const name = `Rq${pad(index)}`
  emit(`const ${name} = Game.System("Stress/${name}", {`)
  emit("  queries: {")
  emit("    held: Game.Query({ selection: { c29: Game.Query.read(C29), c30: Game.Query.read(C30) } }),")
  emit("    whole: Game.Query({ selection: { c28: Game.Query.read(C28) }, with: [C29, C30, C31] })")
  emit("  },")
  emit("  commands: Game.System.commands(Game.System.spawns(C28), Game.System.inserts(C28, C31), Game.System.removes(C28, C29, C30))")
  emit("}, ({ queries, commands }) => {")
  emit(`  const spawned = commands.spawn(Game.Command.spawn([C28, { v28: ${index} }], [C29, { v29: 0 }], [C30, { v30: 0 }], [C31, { v31: 0 }]))`)
  emit("  commands.remove(spawned, C28)")
  emit("  for (const match of queries.held.each()) commands.insert(match.entity, [C28, { v28: 1 }], [C31, { v31: 1 }])")
  emit("  for (const match of queries.whole.each()) commands.remove(match.entity, C28, C29, C30)")
  emit("})")
  requireSystems.push(name)
}
emit(`runtime.tick(Game.Schedule(${requireSystems.join(", ")}, Game.Schedule.applyDeferred()))`)
emit()
emit("const incomplete = Game.Runtime.make({ services: Game.Runtime.services() })")
emit("// @ts-expect-error missing services, resources and machines are compile errors")
emit("incomplete.tick(Update)")
emit()

const target = fileURLToPath(new URL("./stress.ts", import.meta.url))
writeFileSync(target, `${lines.join("\n")}\n`)
